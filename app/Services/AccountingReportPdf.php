<?php

namespace App\Services;

use App\Models\Company;

class AccountingReportPdf
{
    public function render(array $report, Company $company, string $generatedBy): string
    {
        if (in_array($report['type'] ?? '', ['customer_ledger','vendor_ledger'], true)) {
            return $this->renderPartyLedger($report, $company, $generatedBy);
        }

        $pageW = 842.0; $pageH = 595.0; $margin = 32.0; $lineH = 12.0; $fontSize = 8.0;
        $headers = $report['headers']; $colCount = max(1, count($headers));
        $usableW = $pageW - 2*$margin;
        $colW = $usableW / $colCount;
        $pages = []; $page = []; $y = $pageH - $margin;

        $newPage = function () use (&$pages, &$page, &$y, $pageH, $margin, $company, $report, $generatedBy) {
            if ($page) $pages[] = $page;
            $page = [];
            $y = $pageH - $margin;
            $name = $company->legal_name ?: $company->name;
            $page[] = $this->text($margin,$y,13,'B',$name); $y -= 15;
            $contact = trim(implode(' · ', array_filter([$report['branch_label'], $company->address, $company->phone, $company->email])));
            if ($contact !== '') { $page[]=$this->text($margin,$y,7,'R',$contact); $y -= 11; }
            $page[]=$this->text($margin,$y,12,'B',$report['title']); $y -= 14;
            $page[]=$this->text($margin,$y,7,'R','Period: '.$report['from'].' to '.$report['to'].' · Currency: '.$report['currency'].' · Generated by: '.$generatedBy); $y -= 14;
        };
        $newPage();

        $headerRow = function () use (&$page, &$y, $headers, $margin, $colW, $fontSize, $lineH) {
            foreach ($headers as $i=>$h) $page[]=$this->text($margin+$i*$colW,$y,$fontSize,'B',$this->clip($h, $colW, $fontSize));
            $y -= $lineH;
        };
        $headerRow();

        foreach ($report['rows'] as $row) {
            if ($y < $margin + 32) { $newPage(); $headerRow(); }
            foreach ($row['cells'] as $i=>$cell) {
                $page[]=$this->text($margin+$i*$colW,$y,$fontSize,'R',$this->clip((string)$cell, $colW, $fontSize));
            }
            $y -= $lineH;
        }
        if ($y < $margin + 32) { $newPage(); $headerRow(); }
        foreach ($report['totals'] as $i=>$cell) $page[]=$this->text($margin+$i*$colW,$y,$fontSize,'B',$this->clip((string)$cell,$colW,$fontSize));
        $y -= 18;
        $m=$report['metrics'];
        $page[]=$this->text($margin,$y,8,'B','Opening: '.$this->balance((float)$m['opening']).'   Debit: '.number_format((float)$m['debit'],2).'   Credit: '.number_format((float)$m['credit'],2).'   Closing/Difference: '.$this->balance((float)$m['closing']));
        $pages[]=$page;

        return $this->buildPdf($pages, $pageW, $pageH);
    }

    private function renderPartyLedger(array $report, Company $company, string $generatedBy): string
    {
        // A4 portrait. Customer/Vendor ledgers use a compact eight-column statement
        // matching the approved portrait report style.
        $pageW = 595.0; $pageH = 842.0; $margin = 24.0;
        $navy = [0.03,0.16,0.35];
        $pale = [0.91,0.94,0.98];
        $grid = [0.78,0.82,0.87];
        $text = [0.06,0.09,0.15];
        $party = $report['party'];
        $branch = $report['header_branch'] ?? null;
        $headerBranchName = $branch?->name ?: $report['branch_label'];
        $headerAddress = $branch?->address ?: $company->address;
        $headerPhone = $branch?->phone ?: $company->phone;
        $headerEmail = $branch?->email ?: $company->email;
        $headerWebsite = $company->website ?? null;
        $logoJpeg = $this->jpegFromDataUri($company->logo_data_uri ?? null);
        $pages = []; $page = []; $y = 0.0; $pageNo = 0;

        // Total = 547pt, exactly the printable width inside 24pt margins.
        $colWidths = [25,47,75,70,140,55,55,80];
        $tableX = $margin;
        $tableW = array_sum($colWidths);
        $rowH = 18.5;
        $headers = $report['headers'];

        $addCompanyHeader = function(bool $firstPage) use (&$page,&$y,&$pageNo,$pageH,$margin,$company,$report,$generatedBy,$navy,$text,$party,$tableW,$headerBranchName,$headerAddress,$headerPhone,$headerEmail,$headerWebsite,$logoJpeg) {
            $pageNo++;
            $y = $pageH - 26;

            // Company logo comes from Organization > Company Profile.
            if ($logoJpeg) {
                $page[] = $this->imageJpeg($margin,$y-40,52,40,$logoJpeg);
            } else {
                $page[] = $this->rect($margin,$y-40,44,40,[0.97,0.98,1.0],[0.72,0.78,0.86]);
                $code = strtoupper((string)($company->code ?: 'ERP'));
                $page[] = $this->text($margin+10,$y-24,13,'B',$this->clip($code,25,13),$navy);
            }

            $companyName = $company->legal_name ?: $company->name;
            $page[] = $this->text(105,$y-7,16,'B',$this->clip($companyName,390,16),$navy);
            $branchLine = $headerBranchName.($headerAddress ? ' · '.$headerAddress : '');
            $page[] = $this->text(105,$y-21,6.6,'R',$this->clip($branchLine,395,6.6),$text);
            $contact = implode('  |  ', array_filter([
                $headerPhone,
                $headerEmail,
                $headerWebsite ? preg_replace('~^https?://~i','',$headerWebsite) : null,
                $company->tax_registration_no ? 'Tax/Reg: '.$company->tax_registration_no : null,
            ]));
            if ($contact !== '') $page[] = $this->text(105,$y-33,6.2,'R',$this->clip($contact,395,6.2),$text);

            $page[] = $this->line($margin,$y-47,$margin+$tableW,$y-47,$navy,1.2);
            $title = strtoupper((string)($report['party_label'] ?? 'Party')).' LEDGER STATEMENT';
            $page[] = $this->text(185,$y-67,13,'B',$this->clip($title,310,13),$text);

            if ($firstPage) {
                $metaY = $y-88;
                $label = $report['party_label'] ?? 'Party';
                $left = [
                    [$label.' Name',$party->display_name],
                    [$label.' Code',$party->code],
                    ['Branch',$report['branch_label']],
                    ['Currency',$report['currency']],
                ];
                $mid = [
                    ['Date From',date('d M Y',strtotime($report['from']))],
                    ['Date To',date('d M Y',strtotime($report['to']))],
                ];
                if (!empty($report['control_account'])) {
                    $mid[]=['Control A/C',$report['control_account']->code.' · '.$report['control_account']->name];
                }
                $right = [
                    ['Generated On',$report['generated_at']->format('d M Y H:i')],
                    ['Generated By',$generatedBy],
                    ['Page No','Page '.$pageNo],
                ];

                foreach ($left as $i=>$pair) {
                    $yy=$metaY-$i*11;
                    $page[]=$this->text($margin,$yy,6.2,'B',$pair[0],$navy);
                    $page[]=$this->text($margin+58,$yy,6.2,'R',': '.$this->clip((string)$pair[1],105,6.2),$text);
                }
                foreach ($mid as $i=>$pair) {
                    $yy=$metaY-$i*11;
                    $page[]=$this->text(205,$yy,6.2,'B',$pair[0],$navy);
                    $page[]=$this->text(258,$yy,6.2,'R',': '.$this->clip((string)$pair[1],125,6.2),$text);
                }
                foreach ($right as $i=>$pair) {
                    $yy=$metaY-$i*11;
                    $page[]=$this->text(397,$yy,6.2,'B',$pair[0],$navy);
                    $page[]=$this->text(454,$yy,6.2,'R',': '.$this->clip((string)$pair[1],112,6.2),$text);
                }
                $page[] = $this->line($margin,$metaY-49,$margin+$tableW,$metaY-49,[0.55,0.61,0.69],0.6);
                $y = $metaY-60;
            } else {
                $page[] = $this->text(500,$y-66,6.2,'R','Page '.$pageNo,$text);
                $y = $y-80;
            }
        };

        $drawHeader = function() use (&$page,&$y,$headers,$colWidths,$tableX,$tableW,$rowH,$navy,$report) {
            $page[]=$this->rect($tableX,$y-$rowH,$tableW,$rowH,$navy,$navy);
            $x=$tableX;
            foreach($headers as $i=>$h){
                $w=$colWidths[$i]??50;
                $label=$h.(in_array($h,['Debit','Credit','Balance'],true)?' ('.$report['currency'].')':'');
                $page[]=$this->text($x+2,$y-12,5.7,'B',$this->clip($label,$w-4,5.7),[1,1,1]);
                $page[]=$this->line($x,$y,$x,$y-$rowH,[0.38,0.52,0.69],0.4);
                $x+=$w;
            }
            $page[]=$this->line($x,$y,$x,$y-$rowH,[0.38,0.52,0.69],0.4);
            $y-=$rowH;
        };

        $addCompanyHeader(true);
        $drawHeader();

        foreach ($report['rows'] as $row) {
            if ($y < 105) {
                $pages[]=$page; $page=[];
                $addCompanyHeader(false); $drawHeader();
            }
            $fill = !empty($row['is_opening']) ? [0.98,0.985,0.99] : [1,1,1];
            $page[]=$this->rect($tableX,$y-$rowH,$tableW,$rowH,$fill,$grid);
            $x=$tableX;
            foreach($row['cells'] as $i=>$cell){
                $w=$colWidths[$i]??50;
                $isMoney=$i>=5;
                $txt=$this->clip((string)$cell,$w-5,5.9);
                $tx=$x+2.5;
                if($isMoney){
                    $approx=strlen($txt)*2.85;
                    $tx=max($x+2.5,$x+$w-3-$approx);
                }
                $page[]=$this->text($tx,$y-12,5.9,$i===7?'B':'R',$txt,$text);
                $x+=$w;
            }
            $y-=$rowH;
        }

        if ($y < 135) {
            $pages[]=$page; $page=[];
            $addCompanyHeader(false); $drawHeader();
        }

        $page[]=$this->rect($tableX,$y-$rowH,$tableW,$rowH,$pale,[0.35,0.47,0.64]);
        $x=$tableX;
        foreach($report['totals'] as $i=>$cell){
            $w=$colWidths[$i]??50;
            $txt=$this->clip((string)$cell,$w-5,5.9);
            $tx=$x+2.5;
            if($i>=5){
                $approx=strlen($txt)*2.85;
                $tx=max($x+2.5,$x+$w-3-$approx);
            }
            $page[]=$this->text($tx,$y-12,5.9,'B',$txt,$navy);
            $x+=$w;
        }
        $y -= 27;

        $summaryW=$tableW/4;
        $summary=[
            ['Opening Balance',$report['metrics']['opening']],
            ['Total Debit',$report['metrics']['debit']],
            ['Total Credit',$report['metrics']['credit']],
            ['Closing Balance',$report['metrics']['closing']],
        ];
        foreach($summary as $i=>$item){
            $sx=$tableX+$i*$summaryW;
            $page[]=$this->rect($sx,$y-32,$summaryW,32,[1,1,1],$navy);
            $page[]=$this->text($sx+7,$y-11,6.1,'R',$item[0],[0.28,0.34,0.42]);
            $page[]=$this->text($sx+7,$y-25,9.0,'B',number_format(abs((float)$item[1]),2),$text);
        }
        $y -= 47;
        $page[]=$this->text($tableX,$y,5.7,'R','References are clickable in the web view.',[0.28,0.34,0.42]);
        $page[]=$this->text(425,$y,6.1,'R','Prepared By: __________________',$text);
        $pages[]=$page;

        return $this->buildPdf($pages,$pageW,$pageH);
    }

    private function text(float $x,float $y,float $size,string $font,string $text,array $color=[0,0,0]): array
    { return ['op'=>'text','x'=>$x,'y'=>$y,'size'=>$size,'font'=>$font,'text'=>$text,'color'=>$color]; }
    private function line(float $x1,float $y1,float $x2,float $y2,array $color=[0,0,0],float $width=0.5): array
    { return ['op'=>'line','x1'=>$x1,'y1'=>$y1,'x2'=>$x2,'y2'=>$y2,'color'=>$color,'width'=>$width]; }
    private function rect(float $x,float $y,float $w,float $h,array $fill=[1,1,1],array $stroke=[0,0,0]): array
    { return ['op'=>'rect','x'=>$x,'y'=>$y,'w'=>$w,'h'=>$h,'fill'=>$fill,'stroke'=>$stroke]; }

    private function clip(string $text, float $width, float $fontSize): string
    {
        $text = preg_replace('/\s+/u',' ',trim($text));
        $max = max(4, (int)floor($width / ($fontSize * 0.55)));
        $len = function_exists('mb_strlen') ? mb_strlen($text) : strlen($text);
        if ($len > $max) {
            $text = (function_exists('mb_substr') ? mb_substr($text,0,max(1,$max-1)) : substr($text,0,max(1,$max-1))).'...';
        }
        return $text;
    }

    private function balance(float $net): string
    {
        return number_format(abs($net),2).' '.($net>=0?'Dr':'Cr');
    }

    private function imageJpeg(float $x,float $y,float $w,float $h,array $jpeg): array
    {
        return ['op'=>'image_jpeg','x'=>$x,'y'=>$y,'w'=>$w,'h'=>$h,'bytes'=>$jpeg['bytes'],'pixel_w'=>$jpeg['width'],'pixel_h'=>$jpeg['height']];
    }

    private function jpegFromDataUri(?string $dataUri): ?array
    {
        if (!$dataUri || !str_starts_with($dataUri,'data:image/jpeg;base64,')) return null;
        $bytes = base64_decode(substr($dataUri,23), true);
        if ($bytes === false || $bytes === '') return null;
        $size = @getimagesizefromstring($bytes);
        if (!$size || ($size['mime'] ?? '') !== 'image/jpeg') return null;
        return ['bytes'=>$bytes,'width'=>(int)$size[0],'height'=>(int)$size[1]];
    }

    private function buildPdf(array $pages, float $pageW, float $pageH): string
    {
        $objects=[];
        $objects[1]='<< /Type /Catalog /Pages 2 0 R >>';
        $objects[3]='<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>';
        $objects[4]='<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>';
        $pageIds=[]; $next=5;

        foreach($pages as $items){
            $imageObjects=[];
            foreach($items as $idx=>$item){
                if(($item['op']??'')!=='image_jpeg') continue;
                $imageId=$next++;
                $name='Im'.($idx+1);
                $bytes=(string)($item['bytes']??'');
                $pw=max(1,(int)($item['pixel_w']??1));
                $ph=max(1,(int)($item['pixel_h']??1));
                $objects[$imageId]='<< /Type /XObject /Subtype /Image /Width '.$pw.' /Height '.$ph.' /ColorSpace /DeviceRGB /BitsPerComponent 8 /Filter /DCTDecode /Length '.strlen($bytes).' >>' . "\nstream\n".$bytes."\nendstream";
                $imageObjects[$idx]=['id'=>$imageId,'name'=>$name];
            }

            $contentId=$next++;$pageId=$next++;$pageIds[]=$pageId;$stream="";
            foreach($items as $idx=>$item){
                $op=$item['op']??'text';
                if($op==='image_jpeg'){
                    $im=$imageObjects[$idx]??null;
                    if($im){
                        $stream.=sprintf("q %.2F 0 0 %.2F %.2F %.2F cm /%s Do Q\n",$item['w'],$item['h'],$item['x'],$item['y'],$im['name']);
                    }
                    continue;
                }
                if($op==='line'){
                    $c=$item['color']??[0,0,0];$stream.=sprintf("%.3F %.3F %.3F RG %.2F w %.2F %.2F m %.2F %.2F l S\n",$c[0],$c[1],$c[2],$item['width']??0.5,$item['x1'],$item['y1'],$item['x2'],$item['y2']);
                    continue;
                }
                if($op==='rect'){
                    $f=$item['fill']??[1,1,1];$s=$item['stroke']??[0,0,0];
                    $stream.=sprintf("%.3F %.3F %.3F rg %.3F %.3F %.3F RG %.2F %.2F %.2F %.2F re B\n",$f[0],$f[1],$f[2],$s[0],$s[1],$s[2],$item['x'],$item['y'],$item['w'],$item['h']);
                    continue;
                }
                $font=($item['font']??'R')==='B'?'/F2':'/F1';$text=$this->pdfEscape((string)($item['text']??''));$c=$item['color']??[0,0,0];
                $stream.=sprintf("BT %.3F %.3F %.3F rg %s %.2F Tf 1 0 0 1 %.2F %.2F Tm (%s) Tj ET\n",$c[0],$c[1],$c[2],$font,$item['size'],$item['x'],$item['y'],$text);
            }
            $objects[$contentId]='<< /Length '.strlen($stream).' >>' . "\nstream\n".$stream."endstream";
            $xobj='';
            if($imageObjects){
                $pairs=[];
                foreach($imageObjects as $im)$pairs[]='/'.$im['name'].' '.$im['id'].' 0 R';
                $xobj=' /XObject << '.implode(' ',$pairs).' >>';
            }
            $objects[$pageId]='<< /Type /Page /Parent 2 0 R /MediaBox [0 0 '.$pageW.' '.$pageH.'] /Resources << /Font << /F1 3 0 R /F2 4 0 R >>'.$xobj.' >> /Contents '.$contentId.' 0 R >>';
        }
        $objects[2]='<< /Type /Pages /Count '.count($pageIds).' /Kids ['.implode(' ',array_map(fn($id)=>$id.' 0 R',$pageIds)).'] >>';
        ksort($objects);$pdf="%PDF-1.4\n%\xE2\xE3\xCF\xD3\n";$offsets=[0=>0];
        foreach($objects as $id=>$obj){$offsets[$id]=strlen($pdf);$pdf.=$id." 0 obj\n".$obj."\nendobj\n";}
        $xref=strlen($pdf);$max=max(array_keys($objects));$pdf.="xref\n0 ".($max+1)."\n0000000000 65535 f \n";
        for($i=1;$i<=$max;$i++)$pdf.=sprintf('%010d 00000 n ', $offsets[$i]??0)."\n";
        $pdf.="trailer\n<< /Size ".($max+1)." /Root 1 0 R >>\nstartxref\n{$xref}\n%%EOF";
        return $pdf;
    }

    private function pdfEscape(string $text): string
    {
        $text = iconv('UTF-8','Windows-1252//TRANSLIT//IGNORE',$text) ?: $text;
        return str_replace(['\\','(',')',"\r","\n"],['\\\\','\\(','\\)','',' '],$text);
    }
}
