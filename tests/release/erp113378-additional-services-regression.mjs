import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';

const root = path.resolve(import.meta.dirname, '../..');
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');
const routes = read('routes/erp103179.php');
const manager = read('app/Services/Operations/GeneralBookingAdditionalServiceManager.php');
const controller = read('app/Http/Controllers/Operations/GeneralBookingAdditionalServiceController.php');
const index = read('resources/views/operations/bookings/additional-services/index.blade.php');
const show = read('resources/views/operations/bookings/additional-services/show.blade.php');
const hub = read('resources/views/operations/bookings/products-hub-v113304.blade.php');
const lock = read('app/Services/Operations/BookingEditLockResolver.php');

let assertions = 0;
const ok = (condition, message) => { assertions++; assert.ok(condition, message); };

ok(routes.includes("bookings.additional-services.index"), 'index route');
ok(routes.includes("bookings.additional-services.start"), 'start route');
ok(routes.includes("bookings.additional-services.show"), 'show route');
ok(routes.includes("EnforceErpRoleScopedAccess::class"), 'role scope middleware');
const startRoute = routes.slice(routes.indexOf("bookings.additional-services.start") - 500, routes.indexOf("bookings.additional-services.start") + 100);
ok(!startRoute.includes('GuardApprovedGeneralBookingCommercials'), 'start does not use approved-commercial guard');
ok(manager.includes('schema_ready') && manager.includes('General Booking Billing database upgrade'), 'schema missing controlled state');
ok(manager.includes('DB::transaction'), 'start transaction');
ok(manager.includes('lockForUpdate'), 'booking row lock');
ok(manager.includes('GeneralBookingBillingStateResolver'), 'state resolver authority');
ok(manager.includes('NativeSalesInvoiceInspector'), 'native invoice authority');
ok(manager.includes('BookingEditLockResolver'), 'booking lock authority');
ok(manager.includes('GeneralBookingBillingBatchContract'), 'batch contract authority');
ok(manager.includes("'batch_no' => 0") && manager.includes("'batch_type' => 'base'"), 'base adoption sequence/type');
ok(manager.includes("'invoice_sequence' => 0") && manager.includes("'link_type' => 'base'"), 'base link sequence/type');
ok(manager.includes('legacy_invoice_ambiguous') && manager.includes('base_invoice_missing'), 'no-guess legacy outcomes');
ok(manager.includes('base_invoice_still_draft') && manager.includes('base_invoice_pending') && manager.includes('base_invoice_inactive'), 'base status guards');
ok(manager.includes("'batch_type' => 'supplementary'") && manager.includes("'status' => 'draft'"), 'supplementary draft creation');
ok(manager.includes('reused') && manager.includes('approved_uninvoiced'), 'open batch idempotency/guard');
ok(!/general_booking_billing_batch_items[\s\S]{0,120}insert/.test(manager), 'batch item writes remain absent');
ok(!manager.includes('createSalesInvoice') && !/sales_invoices[\s\S]{0,120}insert/.test(manager), 'no native invoice creation');
ok(!manager.includes('journal_entries') && !manager.includes('number_sequences'), 'no accounting writes');
ok(!/travel_status[\s\S]{0,80}update/.test(manager), 'draft does not reset travel readiness');
ok(controller.includes("bookings.additional-services.show") && controller.includes("bookings.additional-services.index"), 'controller navigation');
for (const label of ['Air','Hotel','Transport','Visa','Other Service']) ok(show.includes(label) && show.includes('disabled'), `${label} is disabled next-phase choice`);
ok(index.includes('Total Active Invoiced') && index.includes('Total Posted') && index.includes('Approved Uninvoiced'), 'billing summary');
ok(index.includes('+ Add Product') && index.includes('Continue Additional Services') && index.includes('Pending Approval'), 'index actions');
ok(hub.includes('bookings.additional-services.index') && hub.includes('+ Add Product'), 'smart booking entry');
ok(hub.includes('products.workspace'), 'original product cards preserved');
const allowed = (status) => ['approved', 'travel ready'].includes(status);
ok(allowed('approved') && allowed('travel ready'), 'approved/travel-ready eligibility');
ok(!allowed('draft') && !allowed('reopened') && !allowed('pending approval'), 'draft/reopened/pending blocked');
ok(manager.includes("const OPEN = ['draft', 'pending_approval', 'approved']"), 'one open supplementary set');
ok(lock.includes('Reopen the booking'), 'original booking lock remains native');
console.log(`ERP378 ADDITIONAL SERVICES REGRESSION: PASS (${assertions} assertions)`);
