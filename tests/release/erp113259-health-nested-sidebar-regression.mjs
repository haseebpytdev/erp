import assert from 'node:assert/strict';
import fs from 'node:fs';
const js = fs.readFileSync(new URL('../../public/erp-ui/erp-professional-finalize.js', import.meta.url), 'utf8');
let pass = 0;
const ok = (v, m) => { assert.ok(v, m); pass++; };
